        if (!item.bonus || item.bonus.type === 'none') return null;
        
        const bonusIcons = {
            'health_mult': '💪',
            'damage_mult': '⚔️',
            'armor_mult': '🛡️',
            'gold_mult': '💰',
            'health_regen_mult': '❤️',
            'crit_chance': '🎯',
            'armor_penetration': '💥',
            'vampirism': '🩸'
        };
        
        const value = item.bonus.value * 100;
        const icon = bonusIcons[item.bonus.type] || '✨';
        
        // ⭐ ДРОБНЫЕ ЗНАЧЕНИЯ В ОТОБРАЖЕНИИ
