    isItemOwned(itemId) {
        return this.currentHero && this.currentHero.inventory.includes(itemId);
    }

    addItemToInventory(itemId) {
        if (this.currentHero && !this.currentHero.inventory.includes(itemId)) {
            this.currentHero.inventory.push(itemId);
            return true;
        }
        return false;
    }

